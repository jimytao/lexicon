/** Non-React translation helper (stores, services). Supports `{name}` placeholders. */
export function tStatic(key: string, vars?: Record<string, string | number>): string {
  const appLanguage = useSettingsStore.getState().appLanguage
  let s = translations[appLanguage]?.[key] ?? translations.en[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v))
    }
  }
  return s
}

export function useT(): (key: string) => string {
  const appLanguage = useSettingsStore((s) => s.appLanguage)
  return useCallback(
    (key: string) => translations[appLanguage]?.[key] ?? translations.en[key] ?? key,
    [appLanguage]
  )
}
